CREATE OR REPLACE FUNCTION public.delete_old_gallery_images()
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
  image_record RECORD;
  file_path TEXT;
BEGIN
  -- Loop through all images older than 10 days
  FOR image_record IN
    SELECT id, image_url FROM public.gallery_images WHERE created_at < NOW() - INTERVAL '10 days'
  LOOP
    -- Extract the file path from the full URL (e.g., 'public/my-image.jpg')
    -- This assumes your URL structure is .../gallery_pictures/my-image.jpg
    file_path := (SELECT regexp_matches(image_record.image_url, 'gallery_pictures/(.*)$'))[1];

    -- If a file path was extracted, delete the object from storage
    IF file_path IS NOT NULL THEN
      PERFORM storage.delete_object('gallery_pictures', file_path);
    END IF;

    -- Delete the corresponding record from the gallery_images table
    DELETE FROM public.gallery_images WHERE id = image_record.id;
  END LOOP;
END;
$function$
