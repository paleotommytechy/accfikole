CREATE OR REPLACE FUNCTION public.accf_set_task_completion(p_assignment_id uuid, p_complete boolean)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'auth', 'pg_temp'
AS $function$
declare
  v_user_id uuid := auth.uid();
  v_task_id uuid;
  v_reward integer;
  v_tx_id bigint;
begin
  if v_user_id is null then
    raise exception 'Authentication required';
  end if;

  select ta.task_id, coalesce(t.coin_reward, 0)::integer
  into v_task_id, v_reward
  from public.tasks_assignments ta
  join public.tasks t on t.id = ta.task_id
