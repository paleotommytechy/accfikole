  where id = p_target_user_id;

  insert into public.coin_transactions (
    user_id, source_type, source_id, coin_amount, status, reason
  )
  values (
    p_target_user_id,
    'admin_adjustment',
    'accf:admin-adjustment:' || gen_random_uuid()::text,
    p_amount,
    'approved',
    nullif(trim(coalesce(p_reason, '')), '')
  );
end
