CREATE OR REPLACE FUNCTION public.assign_recurring_tasks()
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
  task_record public.tasks;
  user_record public.profiles;
  task_title text;
  assignment_time timestamptz := NOW();
BEGIN
  -- Loop through tasks that are marked as 'daily' or 'weekly'
  FOR task_record IN
    SELECT * FROM public.tasks
    WHERE
      -- Condition for 'daily' tasks
      frequency = 'daily'
      -- Condition for 'weekly' tasks: assign if today is the same day of the week as the task's creation day
      OR (frequency = 'weekly' AND EXTRACT(ISODOW FROM created_at) = EXTRACT(ISODOW FROM assignment_time))
  LOOP
    task_title := task_record.title;

    -- Loop through all users to assign the task
    FOR user_record IN SELECT id FROM public.profiles LOOP
      -- Check if this task has already been assigned to this user today to prevent duplicates
      IF NOT EXISTS (
        SELECT 1 FROM public.tasks_assignments
        WHERE task_id = task_record.id
          AND assignee_id = user_record.id
          AND created_at >= date_trunc('day', assignment_time)
      ) THEN
        -- Insert the assignment with a due date set to 24 hours from now
        INSERT INTO public.tasks_assignments(task_id, assignee_id, status, created_at, due_date)
        VALUES (task_record.id, user_record.id, 'assigned', assignment_time, assignment_time + interval '1 day');

        -- Create a notification for the user
        INSERT INTO public.notifications(user_id, type, message, link)
        VALUES (user_record.id, 'task_assigned', 'A new ' || task_record.frequency || ' task is due tomorrow: "' || task_title || '"', '/tasks');
      END IF;
    END LOOP;
  END LOOP;
END;
$function$
;
