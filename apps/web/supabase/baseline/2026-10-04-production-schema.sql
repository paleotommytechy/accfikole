CREATE OR REPLACE FUNCTION public.accf_assign_task_to_all_users(p_task_id uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'auth', 'pg_temp'
AS $function$
declare
  v_user record;
  v_task public.tasks%rowtype;
