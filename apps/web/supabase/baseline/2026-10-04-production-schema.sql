CREATE OR REPLACE FUNCTION public.get_chat_history()
 RETURNS TABLE(other_user_id uuid, other_user_name text, other_user_avatar text, last_message_text text, last_message_at timestamp with time zone, unread_count bigint)
 LANGUAGE sql
 SECURITY DEFINER
AS $function$
with conversations as (
    select
        case
            when sender_id = auth.uid() then recipient_id
            else sender_id
        end as other_user_id,
        text,
        message_type, -- Added message_type
        created_at,
        case
            when recipient_id = auth.uid() and is_read = false then 1
            else 0
        end as is_unread
    from messages
    where sender_id = auth.uid() or recipient_id = auth.uid()
),
ranked_conversations as (
    select
        other_user_id,
        text,
        message_type, -- Propagate message_type
        created_at,
        is_unread,
        row_number() over(partition by other_user_id order by created_at desc) as rn
    from conversations
),
latest_messages as (
    select
        other_user_id,
        -- Use a CASE statement to show a placeholder for non-text messages
        case
            when message_type = 'audio' and (text is null or text = '') then 'Sent a voice message'
            else text
        end as last_message_text,
        created_at as last_message_at
    from ranked_conversations
    where rn = 1
),
unread_counts as (
    select
        other_user_id,
        sum(is_unread) as unread_count
    from conversations
    group by other_user_id
)
select
    u.other_user_id,
    p.full_name as other_user_name,
    p.avatar_url as other_user_avatar,
    l.last_message_text,
    l.last_message_at,
    coalesce(u.unread_count, 0) as unread_count
from unread_counts u
join latest_messages l on u.other_user_id = l.other_user_id
join profiles p on u.other_user_id = p.id
order by l.last_message_at desc;
$function$
;
